using CsdiStockHold.Domain;
using Microsoft.EntityFrameworkCore;

namespace CsdiStockHold.Infrastructure;

public sealed class StockHoldDbContext(DbContextOptions<StockHoldDbContext> options) : DbContext(options)
{
    public DbSet<Customer> Customers => Set<Customer>();

    public DbSet<Product> Products => Set<Product>();

    public DbSet<Reservation> Reservations => Set<Reservation>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Customer>(customer =>
        {
            customer.HasKey(c => c.Id);
            customer.Property(c => c.Type).IsRequired();
        });

        modelBuilder.Entity<Product>(product =>
        {
            product.HasKey(p => p.Id);
            product.Property(p => p.Name).IsRequired().HasMaxLength(Product.MaxNameLength);
            product.Property(p => p.StockQuantity).IsRequired();
        });

        modelBuilder.Entity<Reservation>(reservation =>
        {
            // The id is generated by the domain when the reservation is created.
            reservation.HasKey(r => r.Id);
            reservation.Property(r => r.Id).ValueGeneratedNever();
            reservation.Property(r => r.IdempotencyKey)
                .IsRequired()
                .HasMaxLength(Reservation.MaxIdempotencyKeyLength);

            reservation.HasOne<Customer>()
                .WithMany()
                .HasForeignKey(r => r.CustomerId)
                .OnDelete(DeleteBehavior.Restrict);

            reservation.HasOne<Product>()
                .WithMany()
                .HasForeignKey(r => r.ProductId)
                .OnDelete(DeleteBehavior.Restrict);

            // A repeated request (same customer and key) can never create a second reservation.
            reservation.HasIndex(r => new { r.CustomerId, r.IdempotencyKey }).IsUnique();

            // Supports summing a product's active reservations (ProductId = @p AND ExpiresAt > @now).
            reservation.HasIndex(r => new { r.ProductId, r.ExpiresAt }).IncludeProperties(r => r.Quantity);
        });
    }
}
