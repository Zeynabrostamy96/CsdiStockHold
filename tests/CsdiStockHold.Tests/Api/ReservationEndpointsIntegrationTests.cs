using System.Net;
using System.Net.Http.Json;
using CsdiStockHold.Api.Endpoints;
using CsdiStockHold.Tests.Infrastructure;

namespace CsdiStockHold.Tests.Api;

// Integration tests: they need a SQL Server instance (see TestDatabase), so they are excluded from
// the normal run with: dotnet test --filter "Category!=Integration"
// Every test uses its own customers and products and its own fixed time, so the tests of this class
// do not affect each other (the list of expired reservations is checked with "contains", not "equals").
[Trait("Category", "Integration")]
public sealed class ReservationEndpointsIntegrationTests : IClassFixture<TestDatabase>, IDisposable
{
    // No customer or product has this id: ids are generated by the database, starting at 1.
    private const int NonExistingId = int.MaxValue;

    private static readonly DateTimeOffset _startTime = new(2026, 11, 12, 10, 0, 0, TimeSpan.Zero);

    private readonly FixedTimeProvider _time = new(_startTime);
    private readonly ApiFactory _factory;
    private readonly HttpClient _client;

    public ReservationEndpointsIntegrationTests(TestDatabase database)
    {
        _factory = ApiTestSupport.CreateFactory(database, _time);
        _client = _factory.CreateClient();
    }

    public void Dispose()
    {
        _client.Dispose();
        _factory.Dispose();
    }

    [Fact]
    public async Task Reserve_WithValidRequest_Returns201WithLocationAndTheReservation()
    {
        var customerId = await CreateCustomerAsync("Regular");
        var productId = await CreateProductAsync(10);

        var response = await ReserveAsync(customerId, productId, 2, "order-1");

        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        var created = await ReadReservationAsync(response);
        Assert.NotEqual(Guid.Empty, created.Id);
        Assert.Equal(customerId, created.CustomerId);
        Assert.Equal(productId, created.ProductId);
        Assert.Equal(2, created.Quantity);
        Assert.Equal(_startTime, created.CreatedAt);
        Assert.Equal(_startTime.AddMinutes(10), created.ExpiresAt);
        Assert.False(created.IsExpired);
        Assert.Equal($"/api/reservations/{created.Id}", response.Headers.Location?.OriginalString);

        var getResponse = await _client.GetAsync(response.Headers.Location);
        Assert.Equal(HttpStatusCode.OK, getResponse.StatusCode);
        Assert.Equal(created, await ReadReservationAsync(getResponse));
    }

    [Fact]
    public async Task GetProduct_AfterAReservation_ShowsTheReducedAvailableQuantity()
    {
        var customerId = await CreateCustomerAsync("Regular");
        var productId = await CreateProductAsync(10);

        await ReserveAsync(customerId, productId, 2, "order-1");

        var product = await _client.GetFromJsonAsync<ProductResponse>($"/api/products/{productId}", ApiTestSupport.JsonOptions);
        Assert.NotNull(product);
        Assert.Equal(10, product.StockQuantity);
        Assert.Equal(8, product.AvailableQuantity);
    }

    [Fact]
    public async Task Reserve_WhenStockIsInsufficient_Returns409()
    {
        // The example of the specification: 5 units are available and two customers each ask for 4.
        var firstCustomerId = await CreateCustomerAsync("Special");
        var secondCustomerId = await CreateCustomerAsync("Special");
        var productId = await CreateProductAsync(5);

        var first = await ReserveAsync(firstCustomerId, productId, 4, "first-request");
        var second = await ReserveAsync(secondCustomerId, productId, 4, "second-request");

        Assert.Equal(HttpStatusCode.Created, first.StatusCode);
        Assert.Equal(HttpStatusCode.Conflict, second.StatusCode);
        Assert.Equal("InsufficientStock", await ApiTestSupport.ReadProblemCodeAsync(second));
        var product = await _client.GetFromJsonAsync<ProductResponse>($"/api/products/{productId}", ApiTestSupport.JsonOptions);
        Assert.Equal(1, product?.AvailableQuantity);
    }

    [Fact]
    public async Task Reserve_WhenTheCustomerLimitIsExceeded_Returns422()
    {
        // A regular customer may hold at most 3 units in total, whichever products they are.
        var customerId = await CreateCustomerAsync("Regular");
        var firstProductId = await CreateProductAsync(10);
        var secondProductId = await CreateProductAsync(10);

        var first = await ReserveAsync(customerId, firstProductId, 2, "first-product");
        var second = await ReserveAsync(customerId, secondProductId, 2, "second-product");

        Assert.Equal(HttpStatusCode.Created, first.StatusCode);
        Assert.Equal(HttpStatusCode.UnprocessableEntity, second.StatusCode);
        Assert.Equal("CustomerLimitExceeded", await ApiTestSupport.ReadProblemCodeAsync(second));
    }

    [Fact]
    public async Task Reserve_WithAnUnknownCustomer_Returns404()
    {
        var productId = await CreateProductAsync(10);

        var response = await ReserveAsync(NonExistingId, productId, 1, "order-1");

        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
        Assert.Equal("CustomerNotFound", await ApiTestSupport.ReadProblemCodeAsync(response));
    }

    [Fact]
    public async Task Reserve_WithAnUnknownProduct_Returns404()
    {
        var customerId = await CreateCustomerAsync("Regular");

        var response = await ReserveAsync(customerId, NonExistingId, 1, "order-1");

        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
        Assert.Equal("ProductNotFound", await ApiTestSupport.ReadProblemCodeAsync(response));
    }

    [Fact]
    public async Task Reserve_WithAQuantityOfZero_Returns400()
    {
        var customerId = await CreateCustomerAsync("Regular");
        var productId = await CreateProductAsync(10);

        var response = await ReserveAsync(customerId, productId, 0, "order-1");

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
        Assert.Equal("InvalidQuantity", await ApiTestSupport.ReadProblemCodeAsync(response));
    }

    [Fact]
    public async Task Reserve_WithABlankIdempotencyKey_Returns400()
    {
        var customerId = await CreateCustomerAsync("Regular");
        var productId = await CreateProductAsync(10);

        var response = await ReserveAsync(customerId, productId, 1, idempotencyKey: string.Empty);

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
        Assert.Equal("InvalidIdempotencyKey", await ApiTestSupport.ReadProblemCodeAsync(response));
    }

    [Fact]
    public async Task Reserve_WithTheSameRequestAgain_Returns200WithTheOriginalReservation()
    {
        var customerId = await CreateCustomerAsync("Regular");
        var productId = await CreateProductAsync(10);

        var first = await ReserveAsync(customerId, productId, 2, "order-1");
        _time.Advance(TimeSpan.FromMinutes(1));
        var second = await ReserveAsync(customerId, productId, 2, "order-1");

        Assert.Equal(HttpStatusCode.Created, first.StatusCode);
        Assert.Equal(HttpStatusCode.OK, second.StatusCode);
        var original = await ReadReservationAsync(first);
        var repeated = await ReadReservationAsync(second);
        Assert.Equal(original.Id, repeated.Id);
        Assert.Equal(_startTime, repeated.CreatedAt);
        var product = await _client.GetFromJsonAsync<ProductResponse>($"/api/products/{productId}", ApiTestSupport.JsonOptions);
        Assert.Equal(8, product?.AvailableQuantity);
    }

    [Theory]
    [InlineData(false, 3)] // the same product, another quantity
    [InlineData(true, 2)] // another product, the same quantity
    public async Task Reserve_WithTheSameKeyButDifferentContent_Returns422(bool useOtherProduct, int quantity)
    {
        var customerId = await CreateCustomerAsync("Special");
        var productId = await CreateProductAsync(10);
        var otherProductId = await CreateProductAsync(10);
        await ReserveAsync(customerId, productId, 2, "order-1");

        var response = await ReserveAsync(customerId, useOtherProduct ? otherProductId : productId, quantity, "order-1");

        Assert.Equal(HttpStatusCode.UnprocessableEntity, response.StatusCode);
        Assert.Equal("IdempotencyKeyConflict", await ApiTestSupport.ReadProblemCodeAsync(response));
    }

    [Fact]
    public async Task Reserve_WithTheSameKeyAfterTheReservationExpired_Returns200WithTheExpiredOriginal()
    {
        var customerId = await CreateCustomerAsync("Regular");
        var productId = await CreateProductAsync(10);
        var first = await ReserveAsync(customerId, productId, 2, "order-1");

        _time.Advance(TimeSpan.FromMinutes(11));
        var second = await ReserveAsync(customerId, productId, 2, "order-1");

        Assert.Equal(HttpStatusCode.OK, second.StatusCode);
        var original = await ReadReservationAsync(first);
        var repeated = await ReadReservationAsync(second);
        Assert.Equal(original.Id, repeated.Id);
        Assert.True(repeated.IsExpired);
    }

    [Fact]
    public async Task GetExpired_ListsTheExpiredReservationsAndTheirStockIsAvailableAgain()
    {
        var holderId = await CreateCustomerAsync("Regular");
        var waitingCustomerId = await CreateCustomerAsync("Regular");
        var specialCustomerId = await CreateCustomerAsync("Special");
        var scarceProductId = await CreateProductAsync(3);
        var otherProductId = await CreateProductAsync(5);

        var held = await ReadReservationAsync(await ReserveAsync(holderId, scarceProductId, 3, "holder"));
        var stillValid = await ReadReservationAsync(await ReserveAsync(specialCustomerId, otherProductId, 1, "special"));
        var refused = await ReserveAsync(waitingCustomerId, scarceProductId, 1, "waiting-1");
        Assert.Equal(HttpStatusCode.Conflict, refused.StatusCode);

        // 10 minutes after the creation a reservation of a regular customer has expired (a special one lasts 30).
        _time.Advance(TimeSpan.FromMinutes(10));

        var expired = await _client.GetFromJsonAsync<List<ReservationResponse>>("/api/reservations/expired", ApiTestSupport.JsonOptions);
        Assert.NotNull(expired);
        Assert.Contains(expired, r => r.Id == held.Id && r.IsExpired);
        Assert.DoesNotContain(expired, r => r.Id == stillValid.Id);

        var product = await _client.GetFromJsonAsync<ProductResponse>($"/api/products/{scarceProductId}", ApiTestSupport.JsonOptions);
        Assert.Equal(3, product?.AvailableQuantity);
        var retry = await ReserveAsync(waitingCustomerId, scarceProductId, 1, "waiting-2");
        Assert.Equal(HttpStatusCode.Created, retry.StatusCode);
    }

    [Fact]
    public async Task Get_WithAnUnknownReservation_Returns404()
    {
        var response = await _client.GetAsync($"/api/reservations/{Guid.NewGuid()}");

        Assert.Equal(HttpStatusCode.NotFound, response.StatusCode);
    }

    private async Task<int> CreateCustomerAsync(string type)
    {
        var response = await _client.PostAsJsonAsync("/api/customers", new { type });
        var customer = await response.Content.ReadFromJsonAsync<CustomerResponse>(ApiTestSupport.JsonOptions);

        return customer!.Id;
    }

    private async Task<int> CreateProductAsync(int stockQuantity)
    {
        var response = await _client.PostAsJsonAsync("/api/products", new { name = "Laptop", stockQuantity });
        var product = await response.Content.ReadFromJsonAsync<ProductResponse>(ApiTestSupport.JsonOptions);

        return product!.Id;
    }

    private async Task<HttpResponseMessage> ReserveAsync(int customerId, int productId, int quantity, string idempotencyKey)
    {
        using var request = new HttpRequestMessage(HttpMethod.Post, "/api/reservations")
        {
            Content = JsonContent.Create(new { customerId, productId, quantity }),
        };
        request.Headers.Add("Idempotency-Key", idempotencyKey);

        return await _client.SendAsync(request);
    }

    private static async Task<ReservationResponse> ReadReservationAsync(HttpResponseMessage response)
    {
        var reservation = await response.Content.ReadFromJsonAsync<ReservationResponse>(ApiTestSupport.JsonOptions);

        return reservation!;
    }
}
