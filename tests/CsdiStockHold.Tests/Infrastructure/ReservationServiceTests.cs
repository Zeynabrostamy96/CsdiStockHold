using System.Linq.Expressions;
using CsdiStockHold.Domain;
using CsdiStockHold.Infrastructure;
using Microsoft.EntityFrameworkCore;

namespace CsdiStockHold.Tests.Infrastructure;

// Integration tests: they need a SQL Server instance (see TestDatabase), so they are excluded from
// the normal run with: dotnet test --filter "Category!=Integration"
// Every test creates its own customers and products, so the tests of this class do not affect each other.
[Trait("Category", "Integration")]
public class ReservationServiceTests(TestDatabase database) : IClassFixture<TestDatabase>
{
    // No customer or product has this id: ids are generated by the database, starting at 1.
    private const int NonExistingId = int.MaxValue;

    private static readonly DateTimeOffset _startTime = new(2026, 11, 12, 10, 0, 0, TimeSpan.Zero);

    [Fact]
    public async Task ReserveAsync_WithValidRequest_ReturnsAndPersistsTheReservation()
    {
        var time = new FixedTimeProvider(_startTime);
        var customerId = await CreateCustomerAsync(CustomerType.Regular);
        var productId = await CreateProductAsync(10);

        var (reservation, isDuplicate) = await ReserveAsync(time, customerId, productId, 2, "order-1");

        Assert.False(isDuplicate);
        Assert.NotEqual(Guid.Empty, reservation.Id);
        Assert.Equal(customerId, reservation.CustomerId);
        Assert.Equal(productId, reservation.ProductId);
        Assert.Equal(2, reservation.Quantity);
        Assert.Equal("order-1", reservation.IdempotencyKey);
        Assert.Equal(_startTime, reservation.CreatedAt);
        Assert.Equal(_startTime.AddMinutes(10), reservation.ExpiresAt);

        var persisted = Assert.Single(await GetReservationsAsync(r => r.CustomerId == customerId));
        Assert.Equal(reservation.Id, persisted.Id);
        Assert.Equal(productId, persisted.ProductId);
        Assert.Equal(2, persisted.Quantity);
        Assert.Equal("order-1", persisted.IdempotencyKey);
        Assert.Equal(_startTime, persisted.CreatedAt);
        Assert.Equal(_startTime.AddMinutes(10), persisted.ExpiresAt);
        Assert.Equal(2, await GetActiveReservedQuantityAsync(time, productId));
    }

    [Fact]
    public async Task ReserveAsync_WhenStockIsInsufficient_ThrowsInsufficientStockAndPersistsNothing()
    {
        // The example of the specification: 5 units are available and two customers each ask for 4.
        var time = new FixedTimeProvider(_startTime);
        var firstCustomerId = await CreateCustomerAsync(CustomerType.Special);
        var secondCustomerId = await CreateCustomerAsync(CustomerType.Special);
        var productId = await CreateProductAsync(5);

        await ReserveAsync(time, firstCustomerId, productId, 4, "first-request");
        var exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, secondCustomerId, productId, 4, "second-request"));

        Assert.Equal(DomainErrorCode.InsufficientStock, exception.Code);
        Assert.Empty(await GetReservationsAsync(r => r.CustomerId == secondCustomerId));
        Assert.Single(await GetReservationsAsync(r => r.ProductId == productId));
        Assert.Equal(4, await GetActiveReservedQuantityAsync(time, productId));
    }

    [Fact]
    public async Task ReserveAsync_WhenCustomerLimitIsExceededAcrossProducts_ThrowsCustomerLimitExceeded()
    {
        // A regular customer may hold at most 3 units in total, whichever products they are.
        var time = new FixedTimeProvider(_startTime);
        var customerId = await CreateCustomerAsync(CustomerType.Regular);
        var firstProductId = await CreateProductAsync(10);
        var secondProductId = await CreateProductAsync(10);

        await ReserveAsync(time, customerId, firstProductId, 2, "first-product");
        var exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, customerId, secondProductId, 2, "second-product"));

        Assert.Equal(DomainErrorCode.CustomerLimitExceeded, exception.Code);
        Assert.Empty(await GetReservationsAsync(r => r.ProductId == secondProductId));

        // One more unit reaches the limit exactly, so it is accepted.
        var (atLimit, _) = await ReserveAsync(time, customerId, secondProductId, 1, "second-product-at-limit");

        Assert.Equal(1, atLimit.Quantity);
        Assert.Equal(3, (await GetReservationsAsync(r => r.CustomerId == customerId)).Sum(r => r.Quantity));
    }

    [Fact]
    public async Task ReserveAsync_AfterAReservationExpires_ItsStockBecomesAvailableAgain()
    {
        var time = new FixedTimeProvider(_startTime);
        var holderId = await CreateCustomerAsync(CustomerType.Regular);
        var waitingCustomerId = await CreateCustomerAsync(CustomerType.Regular);
        var productId = await CreateProductAsync(3);

        await ReserveAsync(time, holderId, productId, 3, "holder");
        var exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, waitingCustomerId, productId, 1, "waiting-1"));
        Assert.Equal(DomainErrorCode.InsufficientStock, exception.Code);

        // One tick before the expiry (10 minutes for a regular customer) the stock is still held.
        time.Advance(TimeSpan.FromMinutes(10) - TimeSpan.FromTicks(1));
        exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, waitingCustomerId, productId, 1, "waiting-2"));
        Assert.Equal(DomainErrorCode.InsufficientStock, exception.Code);
        Assert.Equal(3, await GetActiveReservedQuantityAsync(time, productId));

        // From the moment of expiry the held units are available again.
        time.Advance(TimeSpan.FromTicks(1));
        Assert.Equal(0, await GetActiveReservedQuantityAsync(time, productId));

        var (reservation, isDuplicate) = await ReserveAsync(time, waitingCustomerId, productId, 1, "waiting-3");

        Assert.False(isDuplicate);
        Assert.Equal(1, reservation.Quantity);
        Assert.Equal(1, await GetActiveReservedQuantityAsync(time, productId));
    }

    [Fact]
    public async Task ReserveAsync_AfterAReservationExpires_ItNoLongerCountsTowardTheCustomerLimit()
    {
        var time = new FixedTimeProvider(_startTime);
        var customerId = await CreateCustomerAsync(CustomerType.Regular);
        var firstProductId = await CreateProductAsync(10);
        var secondProductId = await CreateProductAsync(10);

        // 3 units is the limit of a regular customer.
        await ReserveAsync(time, customerId, firstProductId, 3, "first");

        time.Advance(TimeSpan.FromMinutes(10) - TimeSpan.FromTicks(1));
        var exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, customerId, secondProductId, 1, "second-early"));
        Assert.Equal(DomainErrorCode.CustomerLimitExceeded, exception.Code);

        time.Advance(TimeSpan.FromTicks(1));
        var (reservation, isDuplicate) = await ReserveAsync(time, customerId, secondProductId, 1, "second-late");

        Assert.False(isDuplicate);
        Assert.Equal(1, reservation.Quantity);
    }

    [Fact]
    public async Task ReserveAsync_WithTheSameRequestAgain_ReturnsTheOriginalReservationAsDuplicate()
    {
        var time = new FixedTimeProvider(_startTime);
        var customerId = await CreateCustomerAsync(CustomerType.Regular);
        var productId = await CreateProductAsync(10);

        var (original, firstIsDuplicate) = await ReserveAsync(time, customerId, productId, 2, "order-1");
        time.Advance(TimeSpan.FromMinutes(1));
        var (repeated, secondIsDuplicate) = await ReserveAsync(time, customerId, productId, 2, "order-1");

        Assert.False(firstIsDuplicate);
        Assert.True(secondIsDuplicate);
        Assert.Equal(original.Id, repeated.Id);
        Assert.Equal(original.Quantity, repeated.Quantity);
        Assert.Equal(_startTime, repeated.CreatedAt);
        Assert.Equal(original.ExpiresAt, repeated.ExpiresAt);
        Assert.Single(await GetReservationsAsync(r => r.CustomerId == customerId));
        Assert.Equal(2, await GetActiveReservedQuantityAsync(time, productId));
    }

    [Theory]
    [InlineData(false, 3)] // the same product, another quantity
    [InlineData(true, 2)] // another product, the same quantity
    public async Task ReserveAsync_WithTheSameKeyButDifferentContent_ThrowsIdempotencyKeyConflict(
        bool useOtherProduct,
        int quantity)
    {
        var time = new FixedTimeProvider(_startTime);
        var customerId = await CreateCustomerAsync(CustomerType.Special);
        var productId = await CreateProductAsync(10);
        var otherProductId = await CreateProductAsync(10);
        await ReserveAsync(time, customerId, productId, 2, "order-1");

        var exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, customerId, useOtherProduct ? otherProductId : productId, quantity, "order-1"));

        Assert.Equal(DomainErrorCode.IdempotencyKeyConflict, exception.Code);
        var persisted = Assert.Single(await GetReservationsAsync(r => r.CustomerId == customerId));
        Assert.Equal(productId, persisted.ProductId);
        Assert.Equal(2, persisted.Quantity);
        Assert.Empty(await GetReservationsAsync(r => r.ProductId == otherProductId));
    }

    [Fact]
    public async Task ReserveAsync_WithTheSameKeyAfterTheReservationExpired_ReturnsTheOriginalWithoutCreatingANewOne()
    {
        var time = new FixedTimeProvider(_startTime);
        var customerId = await CreateCustomerAsync(CustomerType.Regular);
        var productId = await CreateProductAsync(10);
        var (original, _) = await ReserveAsync(time, customerId, productId, 2, "order-1");

        time.Advance(TimeSpan.FromMinutes(11));
        var (repeated, isDuplicate) = await ReserveAsync(time, customerId, productId, 2, "order-1");

        Assert.True(isDuplicate);
        Assert.Equal(original.Id, repeated.Id);
        Assert.Equal(_startTime.AddMinutes(10), repeated.ExpiresAt);
        Assert.True(repeated.IsExpired(time.GetUtcNow()));
        Assert.Single(await GetReservationsAsync(r => r.CustomerId == customerId));
        Assert.Equal(0, await GetActiveReservedQuantityAsync(time, productId));
    }

    [Fact]
    public async Task ReserveAsync_WithMissingCustomer_ThrowsCustomerNotFound()
    {
        var time = new FixedTimeProvider(_startTime);
        var productId = await CreateProductAsync(10);

        var exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, NonExistingId, productId, 1, "order-1"));

        Assert.Equal(DomainErrorCode.CustomerNotFound, exception.Code);
        Assert.Empty(await GetReservationsAsync(r => r.ProductId == productId));
    }

    [Fact]
    public async Task ReserveAsync_WithMissingProduct_ThrowsProductNotFound()
    {
        var time = new FixedTimeProvider(_startTime);
        var customerId = await CreateCustomerAsync(CustomerType.Regular);

        var exception = await Assert.ThrowsAsync<DomainException>(
            () => ReserveAsync(time, customerId, NonExistingId, 1, "order-1"));

        Assert.Equal(DomainErrorCode.ProductNotFound, exception.Code);
        Assert.Empty(await GetReservationsAsync(r => r.CustomerId == customerId));
    }

    private async Task<int> CreateCustomerAsync(CustomerType type)
    {
        await using var context = database.CreateContext();
        var customer = new Customer(type);
        context.Customers.Add(customer);
        await context.SaveChangesAsync();

        return customer.Id;
    }

    private async Task<int> CreateProductAsync(int stockQuantity)
    {
        await using var context = database.CreateContext();
        var product = new Product("Laptop", stockQuantity);
        context.Products.Add(product);
        await context.SaveChangesAsync();

        return product.Id;
    }

    // Every request gets its own context and service, like the scope of a web request.
    private async Task<(Reservation Reservation, bool IsDuplicate)> ReserveAsync(
        TimeProvider time,
        int customerId,
        int productId,
        int quantity,
        string idempotencyKey)
    {
        await using var context = database.CreateContext();

        return await new ReservationService(context, time)
            .ReserveAsync(customerId, productId, quantity, idempotencyKey);
    }

    // Reads with a new context, so the result comes from the database and not from a tracked entity.
    private async Task<List<Reservation>> GetReservationsAsync(Expression<Func<Reservation, bool>> where)
    {
        await using var context = database.CreateContext();

        return await context.Reservations.Where(where).ToListAsync();
    }

    private async Task<int> GetActiveReservedQuantityAsync(TimeProvider time, int productId)
    {
        await using var context = database.CreateContext();

        return await new ReservationService(context, time).GetActiveReservedQuantityAsync(productId);
    }
}
